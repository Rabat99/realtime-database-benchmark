-- Gemeinsames Workload-Schema fuer die Hasura- und Zero-Messungen.

CREATE TABLE IF NOT EXISTS topics (
    id          BIGINT PRIMARY KEY,
    name        TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id          BIGINT PRIMARY KEY,
    name        TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id    BIGINT NOT NULL REFERENCES topics(id),
    user_id     BIGINT NOT NULL REFERENCES users(id),
    content     TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    match_value BIGINT NOT NULL
);

-- Zero repliziert ueber den Primary Key, REPLICA IDENTITY FULL ist nicht
-- noetig. Falls das Hasura-Substrat FULL gesetzt hat, hier ebenfalls setzen,
-- damit beide Systeme dieselbe WAL-Menge erzeugen:
